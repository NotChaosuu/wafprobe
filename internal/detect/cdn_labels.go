package detect

type cloudfront struct{}

func (cloudfront) Vendor() string { return "cloudfront" }

func (cloudfront) Detect(resp *Response) *Detection {
	if resp == nil {
		return nil
	}
	var signals []string
	if _, ok := hasHeader(resp.Header, "X-Amz-Cf-Id"); ok {
		signals = append(signals, "header:x-amz-cf-id")
	}
	if v, ok := hasHeader(resp.Header, "Via"); ok && bodyContains([]byte(v), "cloudfront") {
		signals = append(signals, "header:via=cloudfront")
	}
	if len(signals) == 0 {
		return nil
	}
	return cdnLabel(resp, "cloudfront", signals)
}

type fastly struct{}

func (fastly) Vendor() string { return "fastly" }

func (fastly) Detect(resp *Response) *Detection {
	if resp == nil {
		return nil
	}
	var signals []string
	if v, ok := hasHeader(resp.Header, "X-Served-By"); ok && looksLikeFastlyPOP(v) {
		signals = append(signals, "header:x-served-by="+short(v, 24))
	}
	if _, ok := hasHeader(resp.Header, "X-Fastly-Request-ID"); ok {
		signals = append(signals, "header:x-fastly-request-id")
	}
	if len(signals) == 0 {
		return nil
	}
	return cdnLabel(resp, "fastly", signals)
}

type wallarm struct{}

func (wallarm) Vendor() string { return "wallarm" }

func (wallarm) Detect(resp *Response) *Detection {
	if resp == nil {
		return nil
	}
	if s, ok := hasHeader(resp.Header, "Server"); ok && bodyContains([]byte(s), "nginx-wallarm") {
		return blockOr(resp, "wallarm", []string{"header:server=nginx-wallarm"}, resp.StatusCode == 403)
	}
	return nil
}

type modsecurity struct{}

func (modsecurity) Vendor() string { return "modsecurity" }

func (modsecurity) Detect(resp *Response) *Detection {
	if resp == nil {
		return nil
	}
	var signals []string
	if s, ok := hasHeader(resp.Header, "Server"); ok && (bodyContains([]byte(s), "mod_security") || bodyContains([]byte(s), "modsecurity") || bodyContains([]byte(s), "noyb")) {
		signals = append(signals, "header:server=mod_security")
	}
	blocked := false
	if resp.bodyHas("this error was generated by mod_security") ||
		resp.bodyHas("rules of the mod_security module") ||
		resp.bodyHas("protected by mod_security") {
		signals = append(signals, "body:mod_security")
		blocked = true
	}
	if len(signals) == 0 {
		return nil
	}
	det := &Detection{Vendor: "modsecurity", Confidence: "medium", Signals: signals}
	if blocked || resp.StatusCode == 403 || resp.StatusCode == 406 {
		det.Layer = LayerHTTP
		det.Blocked = true
	} else {
		det.Layer = LayerPass
	}
	return det
}

func cdnLabel(resp *Response, vendor string, signals []string) *Detection {
	// a 404 behind CloudFront is a missing page, not a block
	det := &Detection{Vendor: vendor, Confidence: "low", Signals: signals}
	det.Layer, det.Blocked = statusLayer(resp)
	return det
}

func looksLikeFastlyPOP(v string) bool {
	if !hasPrefixFold(v, "cache-") {
		return false
	}
	return len(v) >= 8
}

func init() {
	Register(cloudfront{})
	Register(fastly{})
	Register(wallarm{})
	Register(modsecurity{})
}
