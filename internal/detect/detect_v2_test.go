package detect

import (
	"net/http"
	"testing"
)

func vResp(status int, headers, cookies map[string]string, body string) *Response {
	h := http.Header{}
	for k, v := range headers {
		h.Set(k, v)
	}
	var cs []*http.Cookie
	for k, v := range cookies {
		cs = append(cs, &http.Cookie{Name: k, Value: v})
	}
	return &Response{StatusCode: status, Header: h, Cookies: cs, Body: []byte(body)}
}

func TestNewVendorDetectors(t *testing.T) {
	cases := []struct {
		name       string
		wantVendor string
		r          *Response
	}{
		{"sucuri", "sucuri", vResp(403, map[string]string{"X-Sucuri-ID": "abc"}, nil, "")},
		{"fortiweb-cookie", "fortiweb", vResp(200, nil, map[string]string{"FORTIWAFSID": "x"}, "")},
		{"fortiweb-body", "fortiweb", vResp(403, nil, nil, "<html>fgd_icon</html>")},
		{"netscaler-cookie", "citrix-netscaler", vResp(200, nil, map[string]string{"ns_af": "x"}, "")},
		{"netscaler-mangled", "citrix-netscaler", vResp(200, map[string]string{"Cneonction": "close"}, nil, "")},
		{"radware", "radware", vResp(200, map[string]string{"X-SL-CompState": "x"}, nil, "")},
		{"barracuda", "barracuda", vResp(200, nil, map[string]string{"barra_counter_session": "x"}, "")},
		{"f5-asm-block", "f5-bigip-asm", vResp(200, nil, nil, "The requested URL was rejected. Please consult with your administrator. Support ID: 123")},
		{"wordfence", "wordfence", vResp(503, nil, nil, "Generated by Wordfence")},
		{"azure-front-door", "azure-front-door", vResp(200, map[string]string{"X-Azure-Ref": "x"}, nil, "")},
		{"azure-waf-block", "azure-waf", vResp(403, nil, nil, "<center>Microsoft-Azure-Application-Gateway/v2</center>")},
		{"vercel-challenge", "vercel", vResp(429, map[string]string{"X-Vercel-Mitigated": "challenge"}, nil, "")},
		{"reblaze", "reblaze", vResp(200, nil, map[string]string{"rbzid": "x"}, "")},
		{"queue-it", "queue-it", vResp(200, nil, nil, "assets.queue-it.net/static/challenge/botdetect.min.js")},
		{"arkose", "arkose-labs", vResp(200, nil, nil, `<script src="https://client-api.arkoselabs.com/v2/KEY/api.js"></script>`)},
		{"hcaptcha", "hcaptcha", vResp(200, nil, nil, `<div class="h-captcha" data-sitekey="k"></div>`)},
		{"recaptcha", "recaptcha", vResp(200, nil, nil, `<div class="g-recaptcha"></div>`)},
		{"recaptcha-enterprise", "recaptcha-enterprise", vResp(200, nil, nil, `src="https://www.google.com/recaptcha/enterprise.js?render=K"`)},
		{"friendly-captcha", "friendly-captcha", vResp(200, nil, nil, `<div class="frc-captcha"></div>`)},
		{"cloudfront", "cloudfront", vResp(200, map[string]string{"X-Amz-Cf-Id": "x"}, nil, "")},
		{"fastly", "fastly", vResp(200, map[string]string{"X-Served-By": "cache-lhr7333-LHR"}, nil, "")},
		{"wallarm", "wallarm", vResp(403, map[string]string{"Server": "nginx-wallarm"}, nil, "")},
		{"modsecurity", "modsecurity", vResp(403, nil, nil, "This error was generated by Mod_Security")},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := Analyze(tc.r)
			if got.Vendor != tc.wantVendor {
				t.Errorf("Analyze vendor = %q, want %q (signals %v)", got.Vendor, tc.wantVendor, got.Signals)
			}
		})
	}
}

func TestAtLeast20Vendors(t *testing.T) {
	if n := len(Detectors()); n < 20 {
		t.Errorf("want >= 20 registered detectors, got %d", n)
	}
}

func TestCleanResponseHasNoVendor(t *testing.T) {
	got := Analyze(vResp(200, map[string]string{"Server": "nginx"}, nil, "<html>hello</html>"))
	if got.Vendor != "" {
		t.Errorf("clean response should match no vendor, got %q", got.Vendor)
	}
}

func TestCDNLabelsAreLowConfidence(t *testing.T) {
	for _, v := range []string{"cloudfront", "fastly"} {
		var r *Response
		switch v {
		case "cloudfront":
			r = vResp(200, map[string]string{"X-Amz-Cf-Id": "x"}, nil, "")
		case "fastly":
			r = vResp(200, map[string]string{"X-Served-By": "cache-lhr7333-LHR"}, nil, "")
		}
		if got := Analyze(r); got.Confidence == "high" {
			t.Errorf("%s should be a low-confidence CDN label, got high", v)
		}
	}
}
